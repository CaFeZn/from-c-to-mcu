import { test, expect } from '@playwright/test';
const shot = { animations: 'disabled' as const, style: '.VPNav, .VPLocalNav { visibility: hidden !important; }' };
test('parallel bus visuals track valid words, unknown instructions and blocked writes', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  expect((await page.goto('notes/mcu-architecture'))?.status()).toBe(200);
  const bus = page.getByTestId('mcu-bus-lab');
  await bus.getByTestId('mcu-mode-sram').click();
  await bus.getByTestId('mcu-view-signals').click();
  const signal = bus.getByTestId('bus-signals');
  for (let i = 0; i < 3; i++) await bus.getByTestId('mcu-bus-next').click();
  await expect(signal).toHaveAttribute('data-status', 'valid');
  await expect(signal.getByTestId('signal-word')).toHaveText('0x0000002A');
  await expect(signal.locator('button')).toHaveCount(32);
  await expect(signal.getByTestId('signal-window')).toHaveAttribute('data-level', '1');
  await signal.locator('button').last().click();
  await expect(signal.getByTestId('signal-window')).toHaveAttribute('data-level', '0');
  await bus.getByTestId('mcu-bus-play').click();
  await expect(bus).toHaveAttribute('data-playing', 'true');
  expect(await signal.evaluate(element => element.getAnimations({ subtree: true }).some(animation => animation.playState === 'running'))).toBe(true);
  await bus.getByTestId('mcu-bus-play').click();
  await expect(bus).toHaveAttribute('data-playing', 'false');
  await signal.screenshot({ path: info.outputPath('sram-parallel-signals.png'), ...shot });
  await bus.getByTestId('mcu-mode-flash').click();
  for (let i = 0; i < 3; i++) await bus.getByTestId('mcu-bus-next').click();
  await expect(signal).toHaveAttribute('data-status', 'unmodeled');
  await expect(signal.getByTestId('signal-window')).toHaveAttribute('data-level', 'unknown');
  expect((await page.goto('notes/memory-mapped-io'))?.status()).toBe(200);
  const register = page.getByTestId('register-write-lab');
  await register.getByTestId('register-pin').selectOption('15');
  await register.getByTestId('register-write-value').fill('0x80008000');
  await register.getByTestId('register-view-signals').click();
  for (let i = 0; i < 3; i++) await register.getByTestId('register-step').click();
  const write = register.getByTestId('bus-signals');
  await expect(write).toHaveAttribute('data-status', 'valid');
  await expect(write.getByTestId('signal-word')).toHaveText('0x80008000');
  await expect(write.getByTestId('signal-window')).toHaveAttribute('data-level', '1');
  await write.screenshot({ path: info.outputPath('bsrr-parallel-signals.png'), ...shot });
  await register.getByTestId('register-clock').uncheck();
  await expect(write).toHaveAttribute('data-active', 'false');
  await expect(write.getByTestId('signal-window')).toHaveAttribute('data-level', 'unknown');
  await expect(register.getByTestId('register-odr-current')).toHaveText('0x0000');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  expect(errors).toEqual([]);
});
